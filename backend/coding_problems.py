"""Runnable coding problems: statement in our own words plus a test harness.

`ref` is the widely used name of the problem pattern. The weekly refresh job
matches it against public "asked in the last 30 days" company lists to decide
which problems to prioritise for each company. Statements and tests are
written by us; nothing is copied from problem sites.

Harness fields
- function / params: the function the candidate implements
- kind "class": tests are operation lists run against a class
- compare: exact | sorted (order of a flat list does not matter)
           | groups (order of groups and order inside groups do not matter)
           | float (within 1e-6)
"""

